    monkeypatch.delenv("DEV_MODE", raising=False)
    tc, pool, conn = client
    resp = tc.get("/api/pulse/debug")
    assert resp.status_code == 404
    # No DB query should fire when the gate trips.
    conn.fetchrow.assert_not_awaited()
    conn.fetch.assert_not_awaited()


